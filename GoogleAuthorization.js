
/**
 * JORDS DATALINK
 * Google OAuth authorization service
 */

function getGoogleAuthorizationService_() {
  const properties = PropertiesService.getScriptProperties();

  const clientId = properties.getProperty('OAUTH_CLIENT_ID');
  const clientSecret = properties.getProperty('OAUTH_CLIENT_SECRET');

  if (!clientId || !clientSecret) {
    throw new Error('Google OAuth credentials are missing.');
  }

  return OAuth2.createService('GoogleAppsScriptAPI')
    .setAuthorizationBaseUrl(
      'https://accounts.google.com/o/oauth2/v2/auth'
    )
    .setTokenUrl('https://oauth2.googleapis.com/token')
    .setClientId(clientId)
    .setClientSecret(clientSecret)
    .setCallbackFunction('authCallback')
    .setPropertyStore(PropertiesService.getUserProperties())
    .setScope('https://www.googleapis.com/auth/script.projects')
    .setParam('access_type', 'offline')
    .setParam('prompt', 'consent');
}

/**
 * Handles Google's OAuth callback.
 */
function authCallback(request) {
  const service = getGoogleAuthorizationService_();
  const authorized = service.handleCallback(request);

  if (authorized) {
    return HtmlService.createHtmlOutput(
      'Google authorization successful. You may close this tab.'
    );
  }

  return HtmlService.createHtmlOutput(
    'Google authorization was denied.'
  );
}

function startGoogleAuthorization() {
  const service = getGoogleAuthorizationService_();

  if (service.hasAccess()) {
    Logger.log('Google account is already authorized.');
    return;
  }

  const authorizationUrl = service.getAuthorizationUrl();

  Logger.log('Open this URL to authorize Google access:');
  Logger.log(authorizationUrl);
}

function testGoogleAuthorization() {
  const service = getGoogleAuthorizationService_();

  const authorized = service.hasAccess();

  Logger.log(
    authorized
      ? 'Google authorization is active.'
      : 'Google authorization is not active.'
  );

  return authorized;
}


function testCreateAppsScriptProject() {
  const service = getGoogleAuthorizationService_();

  if (!service.hasAccess()) {
    throw new Error('Google authorization is required.');
  }

  const response = UrlFetchApp.fetch(
    'https://script.googleapis.com/v1/projects',
    {
      method: 'post',
      contentType: 'application/json',
      headers: {
        Authorization: 'Bearer ' + service.getAccessToken()
      },
      payload: JSON.stringify({
        title: 'Jords DataLink API Connection Test'
      }),
      muteHttpExceptions: true
    }
  );

  const statusCode = response.getResponseCode();
  const result = JSON.parse(response.getContentText());

  if (statusCode !== 200) {
    throw new Error(
      'Project creation failed (' + statusCode + '): ' +
      response.getContentText()
    );
  }

  Logger.log('Project created successfully.');
  Logger.log('Project title: ' + result.title);
  Logger.log('Script ID: ' + result.scriptId);

  return result;
}


function testReadGeneratedProject() {
  const service = getGoogleAuthorizationService_();

  const scriptId = '152O_BG0M76yLa3ROHr8zfKCRZDb8ChaX7_NXxIfmtyPmmzd2UXSCKkZs';

  const response = UrlFetchApp.fetch(
    'https://script.googleapis.com/v1/projects/' +
      scriptId + '/content',
    {
      method: 'get',
      headers: {
        Authorization: 'Bearer ' + service.getAccessToken()
      },
      muteHttpExceptions: true
    }
  );

  const statusCode = response.getResponseCode();
  const result = JSON.parse(response.getContentText());

  if (statusCode !== 200) {
    throw new Error(
      'Unable to read project (' + statusCode + '): ' +
      response.getContentText()
    );
  }

  Logger.log('Project content retrieved successfully.');
  Logger.log('Existing files: ' + (result.files || []).length);

  return result;
}

